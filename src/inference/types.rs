use std::collections::HashMap;
use std::path::PathBuf;
use serde::{Deserialize, Serialize};
use crate::config::ModelProfile;

/// Metadata extracted from a local GGUF model header.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct ModelMetadata {
    pub name: String,
    pub architecture: String,
    pub quantization: String,
    pub context_length: usize,
    pub file_size_bytes: u64,
    pub tensor_count: u64,
    pub embedding_length: Option<usize>,
    pub block_count: Option<usize>,
    pub chat_template: Option<String>,
    pub description: Option<String>,
    pub extra_kv: HashMap<String, String>,
}

impl ModelMetadata {
    pub fn new_mock(name: impl Into<String>, arch: impl Into<String>, context_length: usize) -> Self {
        Self {
            name: name.into(),
            architecture: arch.into(),
            quantization: "Q4_K_M".to_string(),
            context_length,
            file_size_bytes: 4 * 1024 * 1024 * 1024,
            tensor_count: 290,
            embedding_length: Some(4096),
            block_count: Some(32),
            chat_template: None,
            description: Some("Mock model for offline tests and development".to_string()),
            extra_kv: HashMap::new(),
        }
    }

    /// Converts this metadata into an initial ModelProfile.
    pub fn into_model_profile(self, file_path: PathBuf) -> ModelProfile {
        let mut profile = ModelProfile::new(self.name.clone(), file_path, self.context_length);
        profile.architecture = Some(self.architecture);
        profile.quantization = Some(self.quantization);
        if let Some(tpl) = self.chat_template {
            profile.custom_template = Some(tpl);
        }
        profile
    }
}

/// Generation runtime parameters.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct GenerationConfig {
    pub max_tokens: usize,
    pub temperature: f32,
    pub top_p: f32,
    pub stop_sequences: Vec<String>,
    pub presence_penalty: f32,
    pub frequency_penalty: f32,
}

impl Default for GenerationConfig {
    fn default() -> Self {
        Self {
            max_tokens: 1024,
            temperature: 0.7,
            top_p: 0.9,
            stop_sequences: vec![
                "<|im_end|>".to_string(),
                "<|endoftext|>".to_string(),
                "</s>".to_string(),
            ],
            presence_penalty: 0.0,
            frequency_penalty: 0.0,
        }
    }
}

/// The reason why generation finished.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub enum StopReason {
    Done,
    MaxTokens,
    StopSequence(String),
    Cancelled,
}

/// Events streamed back to the UI during inference.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub enum GenerationEvent {
    /// Incremental token piece generated by the model.
    Token(String),
    /// Generation completed successfully.
    Complete {
        total_tokens: usize,
        stop_reason: StopReason,
    },
    /// Generation was cancelled by user.
    Cancelled,
    /// An error occurred during generation.
    Error(String),
}

/// Current state of the background inference worker.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub enum WorkerStatus {
    Unloaded,
    Loading { model_name: String },
    Loaded(ModelMetadata),
    Generating { model_name: String },
    Error(String),
}

impl WorkerStatus {
    pub fn is_loaded(&self) -> bool {
        matches!(self, WorkerStatus::Loaded(_) | WorkerStatus::Generating { .. })
    }

    pub fn is_generating(&self) -> bool {
        matches!(self, WorkerStatus::Generating { .. })
    }
}
